#!/usr/bin/env python3
"""Project-local wrapper around F' version generation.

This preserves the standard F' output format while allowing repo-local build
flows to inject explicit framework/project versions for synced target workspaces
that intentionally omit `.git`.
"""

import argparse
import importlib.util
import os
import sys
from pathlib import Path


def load_framework_generator():
    framework_path = os.environ.get("FPRIME_FRAMEWORK_PATH")
    if not framework_path:
        raise RuntimeError("FPRIME_FRAMEWORK_PATH is required for version generation")

    generator_path = (
        Path(framework_path) / "cmake" / "target" / "version" / "generate_version_info.py"
    )
    spec = importlib.util.spec_from_file_location(
        "fprime_framework_version_generator", generator_path
    )
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to load framework version generator: {generator_path}")

    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def env_override(name: str):
    value = os.environ.get(name, "").strip()
    return value if value else None


def create_version_file_cpp(
    output_dir: str, framework_version: str, project_version: str, lib_versions: dict
):
    version_cpp = Path(output_dir) / "version.cpp.tmp"
    with open(version_cpp, "w", encoding="utf-8") as fid:
        fid.write("/*\n")
        fid.write(
            "    This file has been autogenerated using [generate_version_info.py].\n"
        )
        fid.write("    This file may be overwritten.\n")
        fid.write("*/\n")
        fid.write('#include "version.hpp"\n')
        fid.write("\n")
        fid.write("namespace Project {\n\n")
        fid.write(
            f'    const char* const Version::FRAMEWORK_VERSION = "{framework_version}";\n'
        )
        fid.write(
            f'    const char* const Version::PROJECT_VERSION = "{project_version}";\n'
        )
        if len(lib_versions) == 0:
            fid.write("    const FwIndexType Version::LIBRARY_VERSIONS_COUNT = 0; \n")
            fid.write("    const char* const Version::LIBRARY_VERSIONS[] = { \n")
            fid.write("        nullptr\n")
        else:
            fid.write(
                f"    const FwIndexType Version::LIBRARY_VERSIONS_COUNT = {len(lib_versions)}; \n"
            )
            fid.write("    const char* const Version::LIBRARY_VERSIONS[] = { \n")
            for lib_name, version in lib_versions.items():
                fid.write(f'        "{lib_name}@{version}",\n')
        fid.write("    };\n")
        fid.write("}  // namespace Project\n")


def main():
    framework_module = load_framework_generator()

    parser = argparse.ArgumentParser(description="Create version header")
    parser.add_argument(
        "output_dir",
        nargs="?",
        default=".",
        help="Path to write version header into",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        default=False,
        help="Check framework and fallback version",
    )
    args = parser.parse_args()

    framework_version = env_override("FPRIME_FRAMEWORK_VERSION_OVERRIDE")
    if framework_version is None:
        framework_version = framework_module.get_fprime_version()

    project_version = env_override("FPRIME_PROJECT_VERSION_OVERRIDE")
    if project_version is None:
        project_version = framework_module.get_project_version()

    library_versions = framework_module.get_library_versions()
    framework_module.create_version_file_hpp(
        args.output_dir, framework_version, project_version
    )
    create_version_file_cpp(
        args.output_dir, framework_version, project_version, library_versions
    )
    framework_module.create_version_file_json(
        args.output_dir, framework_version, project_version, library_versions
    )

    if args.check and not framework_version.startswith(framework_module.FALLBACK_VERSION):
        expected = framework_version[: len(framework_module.FALLBACK_VERSION)]
        print(
            f"[ERROR] Fallback version {framework_module.FALLBACK_VERSION} not updated. Expected {expected}.",
            file=sys.stderr,
        )
        sys.exit(2)
    sys.exit(0)


if __name__ == "__main__":
    main()
